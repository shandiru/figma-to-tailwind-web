import fs from 'node:fs';
import fsp from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import archiver from 'archiver';
import { env } from '../config/env.js';

const readme = (name) => `# ${name}

Generated by Figma to Tailwind Converter.

## Open
1. Unzip this folder.
2. Double-click \`index.html\` (or serve the folder with any static server, e.g. \`npx serve .\`).

## Notes
- All visual styling uses Tailwind utility classes, including arbitrary values for measured geometry. No inline styles, style blocks or resizing scripts are generated. Tailwind and Google Fonts require internet.
- Images live in \`assets/images/\` as WebP. Keep the folder structure so paths keep working.
- Text and containers are editable HTML elements. Individual artwork layers are WebP assets.
- Layer geometry, fonts and spacing scale fluidly using container-relative units. Mobile is used at base and sm; desktop at md, lg, xl and 2xl when both frames are supplied. The switch is at 768px.
- Buttons are inferred from layer names (Button or CTA). Add click behavior and navigation yourself.
- Custom fonts, masks, blends and advanced image crops may need manual adjustment. See conversion.json for export warnings and counts.
`;

/** Writes output/ to a temp folder, zips it into storage/, removes the temp folder. Returns the zip path. */
export async function createZip(id, name, html, imageFiles, report = {}) {
  const work = await fsp.mkdtemp(path.join(os.tmpdir(), 'f2t-'));
  const root = path.join(work, 'output');
  try {
    await fsp.mkdir(path.join(root, 'assets', 'images'), { recursive: true });
    await fsp.writeFile(path.join(root, 'index.html'), html);
    await fsp.writeFile(path.join(root, 'README.md'), readme(name));
    await fsp.writeFile(path.join(root, 'conversion.json'), JSON.stringify(report, null, 2));
    await Promise.all(imageFiles.map((f) => fsp.writeFile(path.join(root, 'assets', 'images', f.file), f.buffer)));

    await fsp.mkdir(env.storageDir, { recursive: true });
    const zipPath = path.join(env.storageDir, `${id}.zip`);
    await new Promise((resolve, reject) => {
      const stream = fs.createWriteStream(zipPath);
      const archive = archiver('zip', { zlib: { level: 9 } });
      stream.on('close', resolve);
      archive.on('error', reject);
      archive.pipe(stream);
      archive.directory(root, 'output');
      archive.finalize();
    });
    return zipPath;
  } finally {
    await fsp.rm(work, { recursive: true, force: true });
  }
}
