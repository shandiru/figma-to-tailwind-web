import fs from 'node:fs';
import fsp from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import archiver from 'archiver';
import { env } from '../config/env.js';

const readme = (name, format) => `# ${name}

Generated by Figma to Tailwind Converter (${format === 'html' ? 'HTML + Tailwind' : format === 'react' ? 'React + Tailwind' : 'Vue + Tailwind'}).

## Open
${format === 'html' ? '1. Unzip this folder.\n2. Open `index.html` or serve this folder with a static server.' : '1. Unzip this folder.\n2. Run `npm install`, then `npm run dev`.\n3. Open the local URL printed by Vite.'}

## Notes
- All visual styling uses Tailwind utility classes, including arbitrary values for measured geometry. No inline styles, style blocks or resizing scripts are generated. Tailwind and Google Fonts require internet.
- Images live in \`assets/images/\` as WebP. Keep the folder structure so paths keep working.
- Text and containers are editable HTML elements. Individual artwork layers are WebP assets.
- Layer geometry, fonts and spacing scale fluidly using container-relative units. When mobile, tablet, and desktop frames are supplied, they are used at base/sm, md, and lg+ widths respectively. If a size is missing, the nearest supplied layout covers that range.
- Buttons are inferred from layer names (Button or CTA). Add click behavior and navigation yourself.
- Custom fonts, masks, blends and advanced image crops may need manual adjustment. See conversion.json for export warnings and counts.
`;

function frameworkFiles(format, html) {
  const main = html.match(/<main>([\s\S]*?)<\/main>/)?.[1]?.trim() || '';
  const markup = main.replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>')
    .replace(/\bclass=/g, 'className=')
    .replace(/<(area|base|br|col|embed|hr|img|input|link|meta|param|source|track|wbr)(\s[^>]*?)(?<!\/)\s*>/gi, '<$1$2 />');
  if (format === 'react') return {
    'src/App.jsx': `export default function App() {\n  return (\n    <main>${markup}</main>\n  );\n}\n`,
    'src/main.jsx': `import React from 'react';\nimport { createRoot } from 'react-dom/client';\nimport App from './App.jsx';\ncreateRoot(document.getElementById('root')).render(<App />);\n`,
    'package.json': JSON.stringify({ name: 'figma-export-react', private: true, type: 'module', scripts: { dev: 'vite', build: 'vite build' }, dependencies: { '@vitejs/plugin-react': '^5.2.0', vite: '^7.3.7', react: '^18.3.1', 'react-dom': '^18.3.1' } }, null, 2),
    'vite.config.js': `import { defineConfig } from 'vite';\nimport react from '@vitejs/plugin-react';\nexport default defineConfig({ plugins: [react()] });\n`,
  };
  if (format === 'vue') return {
    'src/App.vue': `<template>\n  <main>${main}</main>\n</template>\n`,
    'src/main.js': `import { createApp } from 'vue';\nimport App from './App.vue';\ncreateApp(App).mount('#root');\n`,
    'package.json': JSON.stringify({ name: 'figma-export-vue', private: true, type: 'module', scripts: { dev: 'vite', build: 'vite build' }, dependencies: { '@vitejs/plugin-vue': '^6.0.0', vite: '^7.3.7', vue: '^3.5.0' } }, null, 2),
    'vite.config.js': `import { defineConfig } from 'vite';\nimport vue from '@vitejs/plugin-vue';\nexport default defineConfig({ plugins: [vue()] });\n`,
  };
  return {};
}

/** Writes output/ to a temp folder, zips it into storage/, removes the temp folder. Returns the zip path. */
export async function createZip(id, name, html, imageFiles, report = {}) {
  const format = ['html', 'react', 'vue'].includes(report.format) ? report.format : 'html';
  const work = await fsp.mkdtemp(path.join(os.tmpdir(), 'f2t-'));
  const root = path.join(work, 'output');
  try {
    await fsp.mkdir(path.join(root, 'assets', 'images'), { recursive: true });
    await fsp.writeFile(path.join(root, 'index.html'), html);
    await fsp.writeFile(path.join(root, 'README.md'), readme(name, format));
    if (format !== 'html') {
      const files = frameworkFiles(format, html);
      const title = html.match(/<title>([\s\S]*?)<\/title>/i)?.[1] || 'Figma export';
      const fonts = [...html.matchAll(/<link\s+href="https:\/\/fonts\.googleapis\.com[^>]*>/g)].map(match => match[0]).join('\n');
      const appHtml = `<!doctype html>\n<html lang="en"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1.0"><title>${title}</title>${fonts}<script src="https://cdn.tailwindcss.com"></script></head><body><div id="root"></div><script type="module" src="/src/${format === 'react' ? 'main.jsx' : 'main.js'}"></script></body></html>`;
      await fsp.writeFile(path.join(root, 'index.html'), appHtml);
      for (const [file, contents] of Object.entries(files)) {
        const destination = path.join(root, file);
        await fsp.mkdir(path.dirname(destination), { recursive: true });
        await fsp.writeFile(destination, contents);
      }
      await fsp.writeFile(path.join(root, 'preview.html'), html);
    }
    await fsp.writeFile(path.join(root, 'conversion.json'), JSON.stringify(report, null, 2));
    await Promise.all(imageFiles.map((f) => fsp.writeFile(path.join(root, 'assets', 'images', f.file), f.buffer)));

    await fsp.mkdir(env.storageDir, { recursive: true });
    const zipPath = path.join(env.storageDir, `${id}.zip`);
    await new Promise((resolve, reject) => {
      const stream = fs.createWriteStream(zipPath);
      const archive = archiver('zip', { zlib: { level: 9 } });
      stream.on('close', resolve);
      archive.on('error', reject);
      archive.pipe(stream);
      archive.directory(root, 'output');
      archive.finalize();
    });
    return zipPath;
  } finally {
    await fsp.rm(work, { recursive: true, force: true });
  }
}
